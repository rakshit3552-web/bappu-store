drop policy if exists "Public can view product images" on storage.objects;
create policy "Public can view product images" on storage.objects for select to anon,authenticated using(bucket_id='product-images');
drop policy if exists "Owner can upload product images" on storage.objects;
create policy "Owner can upload product images" on storage.objects for insert to authenticated with check(bucket_id='product-images');
drop policy if exists "Owner can update product images" on storage.objects;
create policy "Owner can update product images" on storage.objects for update to authenticated using(bucket_id='product-images') with check(bucket_id='product-images');
