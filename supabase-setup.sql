create table if not exists public.products(
 id bigint generated by default as identity primary key, name text not null, price numeric not null default 0,
 type text not null default 'kurti', image_url text, sort_order integer not null default 0, created_at timestamptz default now()
);
alter table public.shop_settings enable row level security;
alter table public.products enable row level security;

drop policy if exists "Public can read shop settings" on public.shop_settings;
create policy "Public can read shop settings" on public.shop_settings for select to anon,authenticated using(true);
drop policy if exists "Owner can manage shop settings" on public.shop_settings;
create policy "Owner can manage shop settings" on public.shop_settings for all to authenticated using(true) with check(true);

drop policy if exists "Public can read products" on public.products;
create policy "Public can read products" on public.products for select to anon,authenticated using(true);
drop policy if exists "Owner can manage products" on public.products;
create policy "Owner can manage products" on public.products for all to authenticated using(true) with check(true);

insert into storage.buckets(id,name,public) values('product-images','product-images',true)
